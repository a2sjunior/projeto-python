"""
Operadores de atribuição composta em Python
Definição: Operadores de atribuição composta combinam uma operação aritmética com a atribuição de valor a uma variável.
Exemplos:
x = 10
x += 5   # Equivalente a x = x + 5, agora x é 15
x -= 3   # Equivalente a x = x - 3, agora x é 12
x *= 2   # Equivalente a x = x * 2, agora x é 24
x /= 4   # Equivalente a x = x / 4, agora x é 6.0
x //= 2  # Equivalente a x = x // 2, agora x é 3.0
x %= 2   # Equivalente a x = x % 2, agora x é 1.0
x **= 3  # Equivalente a x = x ** 3, agora x é 1.0
"""